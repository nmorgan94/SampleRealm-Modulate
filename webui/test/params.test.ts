test('every parameter has rows in pluginText', () => {
  for (const { id } of info.params) assert.equal(pluginText.filter(([row]) => row === id).length, 3, id);
});

test('every value reads as the plugin shows it, at the same knob position', () => {
  for (const [id, proportion, text] of pluginText) {
    assert.equal(formatValue(param(id), fromProportion(param(id), proportion)), text, `${id} at ${proportion}`);
  }
});

test('skewed knobs map as JUCE NormalisableRange does, both ways', () => {
  const cutoff = param('filter_cutoff');

  assert.equal(fromProportion(cutoff, 0.5), 2002);
  assert.ok(Math.abs(toProportion(cutoff, fromProportion(cutoff, 0.25)) - 0.25) < 0.001);
});

test('integer and choice positions round halves to even, as roundToInt does', () => {
  assert.equal(fromProportion(param('num_voices'), 0.5), 4);
  assert.equal(fromProportion(param('filter_enable'), 0.5), 0);
  assert.equal(fromProportion(param('filter_mode'), 0.5), 2);
});

test('positions past either end clamp to the range', () => {
  const drive = param('drive');

  assert.equal(fromProportion(drive, 1.5), 1);
  assert.equal(fromProportion(drive, -0.5), 0);
});

test('decimal places follow the step, as AudioParameterFloat counts them', () => {
  assert.deepEqual([0.001, 0.1, 0.01, 1].map(decimalPlaces), [3, 1, 2, 0]);
});

test('typed text parses and snaps, and text without a number is ignored', () => {
  assert.equal(parseValue(param('env1_release'), '0.5'), 0.5);
  assert.equal(parseValue(param('env1_release'), '99'), 5);
  assert.equal(parseValue(param('master_gain'), '-3.14'), -3.1);
  assert.equal(parseValue(param('env1_release'), 'slow'), null);
});
